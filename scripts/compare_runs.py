"""Compare evaluation runs from different models.

Usage:
  python scripts/compare_runs.py qwen2.5-3b-local-cpu nemotron-3-ultra-openrouter-free

Writes evaluation/results/model_comparison.md and evaluation/results/model_comparison.png.
Each run's summary.csv must come from a real (non-mock) run.
"""
from __future__ import annotations

import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "evaluation" / "results"
METHOD_LABELS = {"direct": "Direct LLM", "structured": "Constraint-prompted LLM", "planb": "PlanB",
                 "planb_gold": "PlanB + gold event"}
PANELS = [("task_success", "Task success"), ("booking_f1", "Booking-impact F1"),
          ("cost_exact_match(known)", "Cost exact match (known-cost cases)")]
COLORS = ["#2a78d6", "#eb6834"]  # categorical slots 1-2, validated (CVD ΔE 24.7, contrast >= 3:1)
INK, MUTED, GRID = "#1f1f1e", "#6b6a64", "#e4e3de"


def main(runs: list[str]) -> None:
    frames = []
    for r in runs:
        md = (RESULTS / r / "summary.md").read_text()
        if "MOCK RUN" in md:
            raise SystemExit(f"{r} is a mock run; refusing to compare")
        df = pd.read_csv(RESULTS / r / "summary.csv")
        df["run"] = r
        frames.append(df)
    all_df = pd.concat(frames)

    cols = ["task_success", "feasibility_rate(ok cases)", "booking_f1", "cost_exact_match(known)",
            "infeasible_detected", "avg_latency_s", "avg_tokens"]
    lines = ["# Model comparison (pilot set, 10 scenarios)", "",
             "Generated by `scripts/compare_runs.py` from each run's `summary.csv`.", ""]
    for r, g in all_df.groupby("run", sort=False):
        lines += [f"## `{r}`", "", g[["method"] + cols].round(3).to_markdown(index=False), ""]
    (RESULTS / "model_comparison.md").write_text("\n".join(lines))

    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    methods = list(METHOD_LABELS)
    fig, axes = plt.subplots(1, len(PANELS), figsize=(13, 4.3), sharey=True)
    width = 0.38
    for ax, (metric, title) in zip(axes, PANELS):
        for i, (r, g) in enumerate(all_df.groupby("run", sort=False)):
            vals = [float(g.loc[g.method == m, metric].iloc[0]) if (g.method == m).any() else 0.0 for m in methods]
            xs = [j + (i - 0.5) * (width + 0.02) for j in range(len(methods))]
            bars = ax.bar(xs, vals, width=width, color=COLORS[i % len(COLORS)], label=r, zorder=2)
            if metric == "task_success":
                for b, v in zip(bars, vals):
                    ax.text(b.get_x() + b.get_width() / 2, v + 0.02, f"{v:.0%}", ha="center", va="bottom",
                            fontsize=8, color=INK)
        ax.set_facecolor("#fcfcfb")
        ax.set_title(title, fontsize=11, color=INK, loc="left")
        ax.set_xticks(range(len(methods)), [METHOD_LABELS[m].replace(" ", "\n", 1) for m in methods],
                      fontsize=8, color=MUTED)
        ax.set_ylim(0, 1.12)
        ax.yaxis.grid(True, color=GRID, linewidth=0.8, zorder=0)
        ax.spines[["top", "right", "left"]].set_visible(False)
        ax.spines["bottom"].set_color(GRID)
        ax.tick_params(axis="y", colors=MUTED, labelsize=8, length=0)
        ax.tick_params(axis="x", length=0)
    axes[0].set_ylabel("rate", color=MUTED)
    handles, labels = axes[0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper center", ncols=len(runs), frameon=False, fontsize=9)
    fig.tight_layout(rect=(0, 0, 1, 0.92))
    fig.savefig(RESULTS / "model_comparison.png", dpi=180, facecolor="#fcfcfb")
    plt.close(fig)
    print("wrote", RESULTS / "model_comparison.md", "and", RESULTS / "model_comparison.png")


if __name__ == "__main__":
    main(sys.argv[1:] or ["qwen2.5-3b-local-cpu", "nemotron-3-ultra-openrouter-free"])
